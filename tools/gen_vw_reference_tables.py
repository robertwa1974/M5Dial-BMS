"""Generate test/vw_reference_tables.h from Tom de Bree's VWBMSV2 source.

Usage:
    git clone https://github.com/Tom-evnut/VW-bms.git
    git -C VW-bms checkout 4a6a5b901dd8ee4c443b04fd6376f45d92306de6
    python tools/gen_vw_reference_tables.py VW-bms/VWBMSV2 > test/vw_reference_tables.h

Extracts, without hand-typing:
  - the cell-frame ID -> (module, sub-frame) case table
    (BMSModuleManager::decodecan, BMSModuleManager.cpp:430-718)
  - the balance-command ID pairs for modules 1-12
    (BMSModuleManager::balanceCells, BMSModuleManager.cpp:50-240)
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1], "BMSModuleManager.cpp").read_text(encoding="utf-8", errors="replace")
lines = src.split("\n")

decode = "\n".join(lines[429:718])
cells = re.findall(r"case \((0x[0-9A-Fa-f]+)\):\s*CMU = (\d+);\s*Id = (\d+);", decode)

bal = "\n".join(lines[49:240])
bal_ids = re.findall(r"case \((\d+)\):\s*OUTmsg\.id = (0x[0-9A-Fa-f]+);", bal)
first, second = bal_ids[:12], bal_ids[12:24]
assert len(cells) == 57, len(cells)
assert [int(m) for m, _ in first] == list(range(1, 13))
assert [int(m) for m, _ in second] == list(range(1, 13))

out = [
    "// GENERATED by tools/gen_vw_reference_tables.py from Tom-evnut/VW-bms",
    "// commit 4a6a5b901dd8ee4c443b04fd6376f45d92306de6 - do not edit by hand.",
    "#pragma once",
    "#include <stdint.h>",
    "",
    "struct VwRefCellId { uint32_t id; int module; int sub; };",
    f"static const VwRefCellId VW_REF_CELL_IDS[{len(cells)}] = {{",
]
out += [f"    {{ {i.upper().replace('0X', '0x')}, {c}, {s} }}," for i, c, s in cells]
out += ["};", "", "struct VwRefBalId { int module; uint32_t a; uint32_t b; };",
        "static const VwRefBalId VW_REF_BAL_IDS[12] = {"]
out += [f"    {{ {m}, {a.upper().replace('0X', '0x')}UL, {b.upper().replace('0X', '0x')}UL }},"
        for (m, a), (_, b) in zip(first, second)]
out += ["};", ""]
print("\n".join(out))
