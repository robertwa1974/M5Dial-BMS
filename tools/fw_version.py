# PlatformIO pre-build script: writes src/FwVersion.h with the firmware
# version shown on the serial console, display and web page (and used to
# tell builds apart after a web update).
#
# Version: $FW_VERSION if set (CI sets the tag, or branch@sha), else
# `git describe --tags --always --dirty`, else "v7-dev".
# The header is only rewritten when the version changes, so an unchanged
# version does not trigger a rebuild. It is generated, not committed.
Import("env")
import os
import subprocess


def fw_version():
    v = os.environ.get("FW_VERSION", "").strip()
    if v:
        return v
    try:
        return subprocess.check_output(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=env.subst("$PROJECT_DIR"), stderr=subprocess.DEVNULL,
        ).decode().strip()
    except Exception:
        return "v7-dev"


version = fw_version().replace('"', "").replace("\\", "")[:31]
path = os.path.join(env.subst("$PROJECT_SRC_DIR"), "FwVersion.h")
content = (
    "#pragma once\n"
    "// Generated by tools/fw_version.py - do not edit, not committed\n"
    '#define FW_VERSION "%s"\n' % version
)
old = None
if os.path.exists(path):
    with open(path) as f:
        old = f.read()
if old != content:
    with open(path, "w") as f:
        f.write(content)
print("Firmware version: " + version)
